#!/usr/bin/env bash
#
# Bizuno container entrypoint.
#
# Two responsibilities:
#   1. If env-var-driven configuration is supplied, generate portalCFG.php
#      on first start. This is the production / IaC path: declare DB creds +
#      a fixed BIZUNO_KEY in compose / k8s / your orchestrator, and Bizuno
#      starts ready to go without the interactive installer wizard.
#   2. Make sure runtime directories exist and have the right ownership.
#      Volume mounts come up owned by the host UID; we re-chown to www-data
#      before Apache starts.
#
# If env vars aren't supplied, we leave portalCFG.php absent and the
# pre-flight check in src/portal/installCheck.php routes the user to the
# install wizard on first request — useful for hand-driven dev stacks.

set -euo pipefail

BIZUNO_ROOT="/var/www/html"
PORTAL_CFG="${BIZUNO_ROOT}/portalCFG.php"
SAMPLE_CFG="${BIZUNO_ROOT}/portalCFG-sample.php"
DATA_DIR="${BIZUNO_DATA_DIR:-${BIZUNO_ROOT}/data}"

log() { printf "[bizuno-entrypoint] %s\n" "$*" >&2; }

# ─── 1. Configuration ──────────────────────────────────────────────────────

# Required env for unattended portalCFG.php generation. If any one is
# missing, fall back to web installer flow.
ENV_VARS_PRESENT=true
for v in BIZUNO_DB_HOST BIZUNO_DB_NAME BIZUNO_DB_USER BIZUNO_DB_PASS; do
    if [ -z "${!v:-}" ]; then ENV_VARS_PRESENT=false; break; fi
done

if [ -f "$PORTAL_CFG" ]; then
    log "portalCFG.php already present — leaving as-is"
elif [ "$ENV_VARS_PRESENT" = true ]; then
    log "generating portalCFG.php from environment variables"

    # Generate a per-install BIZUNO_KEY if the user didn't supply one.
    # WARNING: regenerating BIZUNO_KEY across container replacements would
    # invalidate stored encrypted passwords/PII. Persist BIZUNO_KEY across
    # restarts by either setting it explicitly as an env var, or mounting
    # portalCFG.php as a volume.
    if [ -z "${BIZUNO_KEY:-}" ]; then
        BIZUNO_KEY="$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 16)"
        log "BIZUNO_KEY not supplied — generated a fresh one. Set BIZUNO_KEY explicitly in your compose/k8s config to preserve it across container restarts (otherwise encrypted data becomes unreadable on re-create)."
    fi
    BIZUNO_BIZID="${BIZUNO_BIZID:-$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 6)}"
    BIZUNO_DB_PREFIX="${BIZUNO_DB_PREFIX:-}"
    BIZUNO_DB_TYPE="${BIZUNO_DB_TYPE:-mysql}"

    cat > "$PORTAL_CFG" <<PHP
<?php
namespace bizuno;
if (!defined('SCRIPT_START_TIME')) { define('SCRIPT_START_TIME', microtime(true)); }

// ─── Generated by bizuno-entrypoint on first container start ───────────
//
// Values here come from environment variables on the running container.
// To override, either edit this file directly (changes survive container
// restarts because portalCFG.php is persisted on a volume — see compose),
// or set the corresponding env var and delete this file to regenerate.

define('BIZUNO_BIZID',     '${BIZUNO_BIZID}');
define('BIZUNO_KEY',       '${BIZUNO_KEY}');
define('BIZUNO_DB_PREFIX', '${BIZUNO_DB_PREFIX}');
define('BIZUNO_DB_CREDS',  [
    'type'   => '${BIZUNO_DB_TYPE}',
    'host'   => '${BIZUNO_DB_HOST}',
    'name'   => '${BIZUNO_DB_NAME}',
    'user'   => '${BIZUNO_DB_USER}',
    'pass'   => '${BIZUNO_DB_PASS}',
    'prefix' => BIZUNO_DB_PREFIX,
]);
define('BIZUNO_DATA', '${DATA_DIR}/');

// Standard path defines — same as portalCFG-sample.php
if (!defined('BIZUNO_FS_PORTAL'))   { define('BIZUNO_FS_PORTAL',   '${BIZUNO_ROOT}/'); }
if (!defined('BIZUNO_FS_LIBRARY'))  { define('BIZUNO_FS_LIBRARY',  BIZUNO_FS_PORTAL . 'src/'); }
if (!defined('BIZUNO_FS_ASSETS'))   { define('BIZUNO_FS_ASSETS',   BIZUNO_FS_PORTAL . 'vendor/'); }
if (!defined('BIZUNO_URL_PORTAL'))  { define('BIZUNO_URL_PORTAL',  (isset(\$_SERVER['HTTPS']) && \$_SERVER['HTTPS'] === 'on' ? 'https' : 'http') . '://' . \$_SERVER['HTTP_HOST']); }
if (!defined('BIZUNO_URL_AJAX'))    { define('BIZUNO_URL_AJAX',    BIZUNO_URL_PORTAL . '?ajax=1'); }
if (!defined('BIZUNO_URL_API'))     { define('BIZUNO_URL_API',     BIZUNO_URL_PORTAL . '?bizRt='); }
if (!defined('BIZUNO_URL_FS'))      { define('BIZUNO_URL_FS',      BIZUNO_URL_PORTAL . '?bizRt=portal/api/fs&src=' ); }
if (!defined('BIZUNO_URL_VIEW'))    { define('BIZUNO_URL_VIEW',    BIZUNO_URL_PORTAL . '/src'); }
if (!defined('BIZUNO_URL_SCRIPTS')) { define('BIZUNO_URL_SCRIPTS', BIZUNO_URL_PORTAL . '/scripts/'); }

require (BIZUNO_FS_LIBRARY . 'bizunoCFG.php');
require (BIZUNO_FS_LIBRARY . 'portal/controller.php');
PHP
    chown www-data:www-data "$PORTAL_CFG"
    chmod 0640 "$PORTAL_CFG"
else
    log "no portalCFG.php and no DB env vars — web installer will run on first request"
fi

# ─── 2. Filesystem ─────────────────────────────────────────────────────────

# Ensure the data directory exists and is writable. Mounted volumes can come
# up owned by root; force ownership before Apache tries to write to it.
mkdir -p "$DATA_DIR"
chown -R www-data:www-data "$DATA_DIR"
chmod -R u=rwX,g=rwX,o= "$DATA_DIR"

# ─── 3. Hand off ───────────────────────────────────────────────────────────
exec "$@"
